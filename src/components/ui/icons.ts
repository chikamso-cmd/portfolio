const ICONS: Record<string, LucideIcon> = {
  AppWindow,
  Atom,
  Braces,
  Cloud,
  CloudRain,
  Code2,
  Component,
  Database,
  FileJson,
  Gauge,
  GitBranch,
  Layout,
  Link,
  Package,
  Palette,
  Repeat,
  Server,
  Smartphone,
  TrendingUp,
  Wind,
  Zap,
};

export const getIcon = (name: string, fallback: LucideIcon = Code): LucideIcon => ICONS[name] ?? fallback;
